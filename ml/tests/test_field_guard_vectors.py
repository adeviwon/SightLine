def test_the_port_s_assumptions_still_hold():
    """The three Python behaviours the JS has to reproduce, pinned here.

    If any of these changes, the JS is wrong and the vectors below were built on
    a different reference: '%.2f'/'%.10g' round the exact value with ties to
    even, str whitespace is 29 code points (not JS's set), and Python \\w is
    L* + N* + '_' (not JS's ASCII word class).
    """
    assert "%.2f" % 0.125 == "0.12"          # ties to even, not to zero
    assert "%.2f" % 1204.125 == "1204.12"
    assert "%.10g" % 1234567890.5 == "1234567890"
    assert "%.2f" % float("-0") == "-0.00"
    assert "%.2f" % float("9" * 400) == "inf"    # float() overflows in both languages
    assert re.sub(r"\D", "", "١٢٣") == "١٢٣"     # the exclusion, demonstrated
    ws = [c for c in range(0x110000) if re.match(r"\s", chr(c))]
    assert len(ws) == 29 and 0x1C in ws and 0x85 in ws and 0xFEFF not in ws
    assert re.search(r"\bbd\b", "bd\u00fc", re.I) is None    # Python \w is Unicode
    assert re.search(r"\bbd\b", "bd x", re.I) is not None


