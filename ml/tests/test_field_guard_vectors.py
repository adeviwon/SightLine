"""
Golden vectors for the JS port of the field validation + policy layer.

WHY THIS EXISTS
---------------
app/js/field_guard.js is a port of ml/src/field_proximity.py (typed validation,
a spoken reason per rejection) and ml/src/field_policy.py (the speak/refuse
decision). Two implementations of the same rules drift apart the moment one is
edited, and the one a blind user reads is the JS.

So the Python is the reference and the JS is measured against it, on one file of
cases, generated BY the Python:

    app/tools/field_guard_vectors.json   <- this module writes it, nothing else
    app/tools/field_guard_contract.js    <- asserts the JS agrees, case by case

    ./py ml/tests/test_field_guard_vectors.py --write      # regenerate
    ./py -m pytest ml/tests/test_field_guard_vectors.py    # fail if it is stale

WHY A CHECKED-IN FILE AND NOT A GENERATED-ON-THE-FLY ONE
--------------------------------------------------------
The contract must run under plain `node` with no Python and no venv: the vectors
are the artifact that crosses the language boundary, and the pytest below is the
guard that the artifact still belongs to the Python it came from. A stale table
is the only failure mode that would let the two languages silently disagree, so
the staleness check is the point, not an afterthought.

WHAT IS DELIBERATELY NOT IN THE VECTORS
---------------------------------------
Every exclusion below is an input the JAVASCRIPT app cannot receive, not a rule
the JS gets wrong; a rule difference would be a mismatch and this file's job is
to have none. The JS module documents the same list at the top of the file.

  1. NON-ASCII DECIMAL DIGITS. Python's r"\\d" matches Unicode Nd, "²".isdigit()
     is True, and int()/float() parse Nd digits ("١٢٣" -> 123). JS /[0-9]/ and
     Number() are ASCII. Unreachable: the recogniser's output alphabet is
     0-9 A-Z and space (see field_proximity's own note on separator-free dates).
  2. NON-STRING SCALARS in the field maps. str(2500.0) is "2500.0" in Python and
     String(2500.0) is "2500" in JS, and str(list) is not String(array). The
     app's regex path emits strings, which is what the vectors carry.
  3. A `set` AS A regex_fields VALUE. _as_values() iterates it, and Python set
     order is arbitrary, so even the reference is not reproducible run to run
     (it decides which value the "two paths disagree" reason names). Arrays only.
  4. INTEGER-LIKE FIELD NAMES (a field literally called "0"). Python dicts keep
     insertion order, JS objects hoist integer-like keys to the front, and
     candidate order is what breaks a `set`-free decision tie. Field names here
     all resolve through resolve_label, so none of them is numeric.
  5. A NON-STRING KIND. str(True) is "True" in Python, String(true) is "true".
     Kinds are strings in both tables.

Everything the vectors DO cover includes the cases that were actually hard to
port: separator-free and contradictory dates, masked account numbers, empty
values, non-critical kinds, astral characters in the 40-char cap, trailing
whitespace from Python's 29-character whitespace set, exact-format money and
dosage canonicalisation (half-even ties), and integer overflow to "inf".
"""

