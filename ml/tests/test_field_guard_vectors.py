def main():
    ap = argparse.ArgumentParser(description="generate/refresh the field guard vectors")
    ap.add_argument("--write", action="store_true", help="rewrite the vectors file")
    ap.add_argument("--count", action="store_true", help="print the vector count")
    a = ap.parse_args()
    payload = build_vectors()
    n = len(payload["vectors"])
    if a.count:
        print("%d vectors" % n)
        return 0
    if a.write:
        VECTORS.parent.mkdir(parents=True, exist_ok=True)
        VECTORS.write_text(_dump(payload), encoding="utf-8")
        print("wrote %s: %d vectors" % (VECTORS.relative_to(ROOT), n))
        return 0
    ap.print_usage()
    return 1


