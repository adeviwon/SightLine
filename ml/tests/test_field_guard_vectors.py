def _decide_vectors():
    """Scenarios first (each rule fires visibly), then a small option matrix."""
    cases = []

    def add(regex, spot, kinds=None, doc_type=None, strict=False, free=True):
        cases.append({"regex": regex, "spot": spot,
                      "opts": {"kinds": kinds, "doc_type": doc_type,
                               "strict_critical": strict, "speak_free_text": free}})

    # The module's own self-test page: R1, R3, R4, R5 in one prescription.
    page_spot = {
        "date_of_birth": {"value": "04021979", "ok": True, "kind": "date", "reason": "ok"},
        "date": {"value": "01102027", "ok": True, "kind": "date", "reason": "ok"},
        "dosage": {"value": "500mg", "ok": True, "kind": "dosage", "reason": "ok"},
        "pharmacy": {"value": "", "ok": False, "kind": "general",
                     "reason": "no value found after label"},
        "warning": {"value": "MAY", "ok": True, "kind": "general", "reason": "ok"},
        "clause": {"value": "DROWSINESS", "ok": True, "kind": "general", "reason": "ok"},
    }
    page_regex = {"date": "01102026", "dosage": ["500mg", "400mg"]}
    add(page_regex, page_spot, doc_type="prescription")
    add(page_regex, page_spot, doc_type="prescription", strict=True)
    add(page_regex, page_spot)
    add(page_regex, page_spot, doc_type="banking")
    add(page_regex, page_spot, doc_type="general")
    add(page_regex, page_spot, doc_type="")
    add(page_regex, page_spot, doc_type="prescription", free=False)
    add(page_regex, {}, doc_type="prescription")
    add({}, page_spot, doc_type="prescription")
    add({}, {}, doc_type="prescription")

    # R3 contradiction, both directions and at both digit lengths.
    add({"date": "01102026"}, {"date": {"value": "01102027", "ok": True, "kind": "date", "reason": "ok"}})
    add({"date": "01102026"}, {"date": {"value": "01102026", "ok": True, "kind": "date", "reason": "ok"}})
