def _validate_vectors():
    out = []
    corpus = {
        "date": _date_values(),
        "money": _money_values(),
        "dosage": _dosage_values(),
        "account": _account_values(),
        "sort_code": _sort_code_values(),
        "identifier": _identifier_values(),
        "general": _general_values(),
    }
    for kind, values in corpus.items():
        for v in values:
            ok, reason = FP.validate(kind, v)
            out.append({"t": "validate", "kind": kind, "value": v,
                        "ok": ok, "reason": reason})
    # Non-string and missing values: validate() must never raise.
    #
    # EXCLUDED HERE (see UNPORTABLE, "non-string-kind"): validate(None, "x").
    # Both languages refuse it with the same rule, but the reason ECHOES the
    # kind, and Python's %-format renders None as "None" while String(null) is
    # "null" ("unknown kind: None" vs "unknown kind: null"). Emulating Python
    # repr() for a kind that is always a string in both tables is not worth the
    # code, so the case is left out rather than papered over. The unknown-kind
    # vector below keeps the rule itself covered.
    for kind, value in [("date", None), ("general", None),
                        ("nope", "x"), ("date", ""), ("general", "")]:
        ok, reason = FP.validate(kind, value)
        out.append({"t": "validate", "kind": kind, "value": value,
                    "ok": ok, "reason": reason})
    return out


