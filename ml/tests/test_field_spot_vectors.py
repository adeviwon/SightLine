"""Golden vectors for the JS port of the label spotter + the proximity read.

WHY THIS EXISTS
---------------
app/js/field_spot.js is a port of ml/src/label_spot.py (spot_labels,
spot_in_lines) and the PROXIMITY READ half of ml/src/field_proximity.py
(_trim_index, value_after, _next_line_text, extract_fields). Two implementations
of the same rules drift apart the moment one is edited, and the one a blind user
reads is the JS.

So the Python is the reference and the JS is measured against it, on one file of
cases, generated BY the Python:

    app/tools/field_spot_vectors.json   <- this module writes it, nothing else
    app/tools/field_spot_contract.js    <- asserts the JS agrees, case by case

    ./.venv/bin/python ml/tests/test_field_spot_vectors.py --write   # regenerate
    ./.venv/bin/python -m pytest ml/tests/test_field_spot_vectors.py -q  # stale check

THE VOCABULARY IS GENERATED, NOT TYPED
--------------------------------------
The JS module's VOCAB / CONFUSE / SEP live in a @generated block that this
module writes into app/js/field_spot.js between two markers, straight from
ml/src/label_spot.py (DOC_LABELS -> VOCAB, _CONFUSE) and
ml/src/field_proximity.py (_SEP). test_the_js_vocabulary_is_generated proves
that block is byte-identical to what the Python produces today AND that every
label traces to a repo source through label_spot.provenance() (capture.DOCS /
evaluate.classify_doc / field_lexicon.PATTERNS), so the two vocabularies cannot
drift and the JS list cannot have been hand-typed.

WHAT IS DELIBERATELY NOT IN THE VECTORS
---------------------------------------
Every exclusion below is an input the JS app CANNOT receive, not a rule the JS
gets wrong; a rule difference would be a mismatch and this file's job is to have
none. They are the UNPORTABLE list below, named with a reason and asserted by
test_unportable_inputs_are_named.
"""

