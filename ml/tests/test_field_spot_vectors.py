def _spot_texts():
    texts = list(HAND_TEXT)
    for lab in LS.VOCAB:
        texts.append(lab)
        texts.append(lab + ": 1234")
        texts.append(lab.lower())
        texts.append(lab + "S")            # must NOT fire: inside a longer token
        texts.append("X" + lab)            # must NOT fire: preceded by a letter
        texts += _perturbations(lab)
    # Deduplicate, preserving order: a smaller table is a smaller contract.
    seen, out = set(), []
    for t in texts:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out


def _spot_vectors():
    texts = _spot_texts()
    out = []
    for t in texts:
        out.append({"t": "spot", "text": t, "threshold": 0.75,
                    "spots": LS.spot_labels(t, 0.75)})
    # The measured-best threshold, on the same corpus: same recall, fewer spots.
    for t in texts:
        out.append({"t": "spot", "text": t, "threshold": 0.833,
                    "spots": LS.spot_labels(t, 0.833)})
    return out


