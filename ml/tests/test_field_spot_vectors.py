def _value_vectors():
    rows = [
        ("Sort Code: 40-11-04", (0, 9)),
        ("Sort Code:40-11-04", (0, 9)),
        ("Sort Code    40 11 04", (0, 9)),
        ("Sort Code:\t40-11-04", (0, 9)),
        ("Sort Code:#=|.40-11-04", (0, 9)),
        ("Sort Code: -1,100.00", (0, 9)),
        ("Sort Code:40-11-04", (0, 9)),
        ("Sort Code", (0, 9)),
        ("Sort Code:", (0, 9)),
        ("Sort Code:   ", (0, 9)),
        ("", (0, 0)),
        ("Account Number: **** 4521", (0, 14)),
        ("Dosage: 500mg", (0, 6)),
        # Python's 29-code-point whitespace set at the right edge: rstrip trims
        # ' \xa0 \x85', never '\ufeff'. These catch a port that used JS trim().
        ("Sort Code: 40-11-04 \xa0\x85 ", (0, 9)),
        ("Sort Code: 40-11-04\ufeff", (0, 9)),
        # A leading non-separator whitespace is KEPT by rstrip (it is not in
        # _SEP): this is what tells rstrip apart from strip.
        ("Sort Code: \xa040-11-04", (0, 9)),
        ("Sort Code:\x1c40-11-04", (0, 9)),
        ("TERM: 24 months from 1 February 2024", (0, 4)),
        ("Opening Balance        GBP 1,204.33", (0, 15)),
    ]
    out = []
    for text, span in rows:
        out.append({"t": "value", "text": text, "span": list(span),
                    "value": FP.value_after(text, span)})
    return out


def _lines(rows):
    return [{"text": t, "box": [x0, y, x0 + 300, y + 20]} for t, x0, y in rows]


def _spots(rows, labels):
    out = []
    for li, lab in labels:
        t = rows[li][0]
        i = t.find(lab)
        out.append({"label": lab, "start": i, "end": i + len(lab), "score": 0.9,
                    "line_index": li})
    return out


def _extract(name, rows, labels):
    lines = _lines(rows)
    spots = _spots(rows, labels)
    return {"t": "extract", "name": name, "lines": lines, "spots": spots,
            "out": FP.extract_fields(lines, spots)}


def _extract_vectors():
    out = []
    # field_proximity's own self-test cases, reproduced through the reference.
    for name, lines, spots in FP.CASES:
        out.append({"t": "extract", "name": name, "lines": lines, "spots": spots,
                    "out": FP.extract_fields(lines, spots)})

    out.append(_extract("masked account", [("Account Number: **** 4521", 40, 20)],
                        [(0, "Account Number")]))
    out.append(_extract("next-line with box",
                        [("Account Number:", 40, 20), ("40218877", 40, 50)],
                        [(0, "Account Number")]))
    out.append(_extract("next-line two rows down out of order",
                        [("Sort Code:", 40, 90), ("nothing here", 40, 20),
                         ("40-11-04", 40, 120)],
                        [(0, "Sort Code")]))
    out.append(_extract("two labels one line",
                        [("Account Number: 40218877   Sort Code: 40-11-04", 40, 20)],
                        [(0, "Account Number"), (0, "Sort Code")]))
    out.append(_extract("no value, no next line",
                        [("Sort Code:", 40, 20)],
                        [(0, "Sort Code")]))
    out.append(_extract("label with nothing after it and a blank next line",
                        [("Sort Code:", 40, 20), ("   ", 40, 50)],
                        [(0, "Sort Code")]))
    out.append(_extract("value with no label (COURT resolves to a slug)",
                        [("COURT: 2024-CV-00456", 40, 20)],
                        [(0, "COURT")]))
    out.append(_extract("prescription page",
                        [("PRESCRIPTION", 40, 20), ("PATIENT: JANE DOE", 40, 50),
                         ("DOB: 04/02/1979", 40, 80), ("Dosage: 500mg", 40, 110),
                         ("Warning: may cause drowsiness", 40, 140)],
                        [(0, "PRESCRIPTION"), (1, "PATIENT"), (2, "DOB"),
                         (3, "Dosage"), (4, "Warning")]))
    out.append(_extract("banking page",
                        [("HSBC UK BANK PLC", 40, 20),
                         ("Account Number: 40218877", 40, 50),
                         ("Sort Code: 40-11-04", 40, 80),
                         ("Opening Balance        GBP 1,204.33", 40, 110)],
                        [(0, "HSBC UK BANK PLC"), (1, "Account Number"),
                         (2, "Sort Code"), (3, "Opening Balance")]))
    out.append(_extract("legal page",
                        [("LEASE AGREEMENT", 40, 20),
                         ("TENANT: JANE DOE", 40, 50),
                         ("TERM: 24 months from 1 February 2024", 40, 80),
                         ("Case Reference: 2024-CV-00456", 40, 110)],
                        [(0, "LEASE AGREEMENT"), (1, "TENANT"), (2, "TERM"),
                         (3, "Case Reference")]))

    # Determinism: shuffled spots give the same dict.
    rows = [("Account Number: 40218877   Sort Code: 40-11-04", 40, 20)]
    lines = _lines(rows)
    spots = _spots(rows, [(0, "Account Number"), (0, "Sort Code")])
    shuffled = [spots[1], spots[0]]
    out.append({"t": "extract", "name": "shuffled spots",
                "lines": lines, "spots": shuffled,
                "out": FP.extract_fields(lines, shuffled)})

    # Edge inputs that must not raise and must produce the same empty/partial map.
    out.append({"t": "extract", "name": "empty", "lines": [], "spots": [],
                "out": FP.extract_fields([], [])})
    out.append({"t": "extract", "name": "spots with no lines", "lines": [],
                "spots": [{"label": "Sort Code", "start": 0, "end": 9,
                           "score": 0.9, "line_index": 0}],
                "out": FP.extract_fields([], [{"label": "Sort Code", "start": 0,
                                               "end": 9, "score": 0.9,
                                               "line_index": 0}])})
    out.append({"t": "extract", "name": "line_index out of range",
                "lines": [{"text": "Sort Code: 40-11-04", "box": [0, 0, 10, 10]}],
                "spots": [{"label": "Sort Code", "start": 0, "end": 9, "score": 0.9,
                           "line_index": 7}],
                "out": FP.extract_fields(
                    [{"text": "Sort Code: 40-11-04", "box": [0, 0, 10, 10]}],
                    [{"label": "Sort Code", "start": 0, "end": 9, "score": 0.9,
                      "line_index": 7}])})
    out.append({"t": "extract", "name": "lines without a box use the next index",
                "lines": [{"text": "Account Number:"}, {"text": "40218877"}],
                "spots": [{"label": "Account Number", "start": 0, "end": 14,
                           "score": 0.9, "line_index": 0}],
                "out": FP.extract_fields(
                    [{"text": "Account Number:"}, {"text": "40218877"}],
                    [{"label": "Account Number", "start": 0, "end": 14,
                      "score": 0.9, "line_index": 0}])})

    # Integration shape: spots produced by the spotter itself, straight in.
    for name, rows, th in [
        ("integrated banking", [("SORT C0DE 40-11-04", 40, 20),
                                ("ACC0UNT N0MBER", 40, 50),
                                ("40218877", 40, 80)], 0.75),
        ("integrated prescription", [("PRESCRIPTION", 40, 20),
                                     ("Dosage: 500 MG per day", 40, 50)], 0.75),
        ("integrated at 0.833", [("ACC0UNT N0MBER 40218877", 40, 20)], 0.833),
    ]:
        lines = _lines(rows)
        spots = []
        for i, (t, _x, _y) in enumerate(rows):
            for s in LS.spot_labels(t, th):
                s = dict(s)
                s["line_index"] = i
                spots.append(s)
        out.append({"t": "extract", "name": name, "lines": lines, "spots": spots,
                    "out": FP.extract_fields(lines, spots)})
    return out


def build_vectors():
    """The whole golden table. Deterministic: no sets, no dict-order dependence.

    Normalised through JSON once: field_proximity.CASES carry box TUPLES, which
    json.loads reads back as lists, so the checked-in file and this function
    would otherwise never compare equal in Python (the JS sees lists on both
    sides and is unaffected)."""
    vectors = []
    vectors += _spot_vectors()
    vectors += _lines_vectors()
    vectors += _value_vectors()
    vectors += _extract_vectors()
    return json.loads(json.dumps({"vectors": vectors}))


# ── the generated JS vocabulary block ─────────────────────────────────────────

def build_js_block():
    """The exact text between the @generated markers in app/js/field_spot.js.

    Straight from the Python: VOCAB is label_spot.VOCAB (DOC_LABELS, which
    provenance() traces to capture.DOCS / evaluate.classify_doc /
    field_lexicon.PATTERNS), CONFUSE is label_spot._CONFUSE and SEP is
    field_proximity._SEP. Nothing here is typed by hand."""
    lines = [
        "  // ── VOCABULARY — GENERATED from ml/src/label_spot.py (DOC_LABELS,",
        "  //    _CONFUSE), traced through provenance() to ml/src/field_lexicon.py",
        "  //    PATTERNS + capture.DOCS + evaluate.classify_doc, and",
        "  //    ml/src/field_proximity.py (_SEP). DO NOT HAND-EDIT. Regenerate:",
        "  //      ./.venv/bin/python ml/tests/test_field_spot_vectors.py --write",
        "  const VOCAB = [",
    ]
    for lab in LS.VOCAB:
        lines.append('    "%s",' % lab)
    lines.append("  ];")
    lines.append("  const CONFUSE = %s;"
                 % json.dumps(dict(LS._CONFUSE), separators=(",", ":")))
    # SEP literally, escaping only the tab and the two non-ASCII characters.
    parts = []
    for c in FP._SEP:
        if c == "\t":
            parts.append("\\t")
        elif ord(c) > 126:
            parts.append("\\u%04x" % ord(c))
        else:
            parts.append(c)
    lines.append('  const SEP = "%s";' % "".join(parts))
    return "\n".join(lines) + "\n"


def _read_js():
    return JS.read_text(encoding="utf-8")


def js_block_in_file(src):
    a = src.index(GEN_BEGIN) + len(GEN_BEGIN)
    b = src.index(GEN_END)
    return src[a:b]


def _write_js_block(block):
    src = _read_js()
    a = src.index(GEN_BEGIN) + len(GEN_BEGIN)
    b = src.index(GEN_END)
    JS.write_text(src[:a] + block + src[b:], encoding="utf-8")


# ── tests ─────────────────────────────────────────────────────────────────────

def test_vectors_are_fresh():
    """The checked-in table is exactly what the Python produces today."""
    want = build_vectors()
    got = json.loads(VECTORS.read_text(encoding="utf-8"))
    assert got == want, (
        "app/tools/field_spot_vectors.json is stale — regenerate it with "
        "./.venv/bin/python ml/tests/test_field_spot_vectors.py --write"
    )


def test_corpus_is_substantial_and_covers_every_vector_type():
    vectors = build_vectors()["vectors"]
    assert len(vectors) >= 300, "the brief asks for hundreds of cases, got %d" % len(vectors)
    kinds = {v["t"] for v in vectors}
    assert kinds == {"spot", "lines", "value", "extract"}, kinds
    # every label family is present as a spot vector
    for lab in LS.VOCAB:
        assert any(v["t"] == "spot" and v["text"] == lab for v in vectors), lab


def test_both_outcomes_are_exercised():
    """A table where every spot or extraction is empty would pass trivially."""
    vectors = build_vectors()["vectors"]
    assert sum(1 for v in vectors if v["t"] == "spot" and v["spots"]) >= 100
    assert sum(1 for v in vectors if v["t"] == "spot" and not v["spots"]) >= 50
    outs = [v["out"] for v in vectors if v["t"] == "extract"]
    fields = [r for o in outs for r in o.values()]
    assert sum(1 for r in fields if r["ok"]) >= 10
    assert sum(1 for r in fields if not r["ok"]) >= 10
    provs = {r["provenance"] for r in fields}
    assert {"same-line-right", "next-line", "none"} <= provs, provs


def test_threshold_is_exercised():
    vectors = build_vectors()["vectors"]
    ths = {v["threshold"] for v in vectors if v["t"] == "spot"}
    assert ths == {0.75, 0.833}, ths
    # ...and the two thresholds actually differ somewhere (a near-threshold miss).
    by_text = {}
    for v in vectors:
        if v["t"] == "spot":
            by_text.setdefault(v["text"], {})[v["threshold"]] = v["spots"]
    assert any(x.get(0.75) != x.get(0.833) for x in by_text.values())


def test_the_js_vocabulary_is_generated():
    """The JS block is byte-identical to the Python's, and traces to disk.

    This is the proof the brief asks for: the JS vocabulary is GENERATED from
    the Python source rather than hand-typed, and the two cannot drift.
    """
    src = _read_js()
    assert js_block_in_file(src) == build_js_block(), (
        "app/js/field_spot.js's @generated vocabulary block is stale — regenerate "
        "it with ./.venv/bin/python ml/tests/test_field_spot_vectors.py --write"
    )
    import re
    block = js_block_in_file(src)
    js_vocab = re.findall(r'^\s*"([^"]+)",$', block, re.M)
    assert js_vocab == list(LS.VOCAB), (js_vocab, list(LS.VOCAB))
    assert len(js_vocab) == len(LS.VOCAB) == len(set(js_vocab))
    # every label came off disk: label_spot.provenance() names where
    prov = LS.provenance()
    assert all(v is not None for v in prov.values()), prov
    assert "field_lexicon.PATTERNS" in {v for v in prov.values() if v}, \
        sorted({v for v in prov.values() if v})


def test_the_js_carries_no_lookbehind():
    """Safari < 16.4 throws a PARSE-TIME SyntaxError on it and loses the file."""
    src = _read_js()
    assert "(?<" not in src, "a backwards-assertion construct is in app/js/field_spot.js"


def test_unportable_inputs_are_named():
    """The exclusions are part of the deliverable: they are why the JS is smaller."""
    assert len(UNPORTABLE) >= 4
    for name, reason in UNPORTABLE:
        assert name and len(reason) > 30, name
    # The exclusions are real, not hypothetical: show each on the Python side.
    assert len("e\U0001D552") == 2                       # astral is 1 Python code point
    assert any(unicodedata.category(c) == "Nd" and ord(c) > 127
               for c in "\u0661\u0662\u0663")
    assert "\u0661".isdigit()                             # Arabic-Indic digit, Python \d
    assert "\u0130".lower() != "\u0130"                   # case folding is not 1:1
    # ...and no vector carries the unreachable characters.
    for v in build_vectors()["vectors"]:
        for s in (v.get("text"), v.get("value")):
            if isinstance(s, str):
                assert not any(ord(c) > 0xFFFF for c in s), repr(s)
                assert not any(unicodedata.category(c) == "Nd" and ord(c) > 127
                               for c in s), repr(s)


def test_vectors_json_is_what_the_contract_reads():
    assert VECTORS.exists(), "run ./.venv/bin/python ml/tests/test_field_spot_vectors.py --write"
    payload = json.loads(VECTORS.read_text(encoding="utf-8"))
    assert payload == build_vectors()


def test_the_port_s_assumptions_still_hold():
    """The behaviours the JS has to reproduce, pinned here."""
    # Python's whitespace set is 29 code points and excludes \ufeff.
    import re
    ws = [c for c in range(0x110000) if re.match(r"\s", chr(c))]
    assert len(ws) == 29 and 0x1C in ws and 0x85 in ws and 0xFEFF not in ws
    # rstrip trims \xa0 and \x85 but not a leading one (that is strip's job).
    assert FP.value_after("Sort Code: 40-11-04 \xa0\x85 ", (0, 9)) == "40-11-04"
    assert FP.value_after("Sort Code: \xa040-11-04", (0, 9)) == "\xa040-11-04"
    # the vocabulary is closed and sourced
    assert len(LS.VOCAB) == 37, len(LS.VOCAB)
    assert LS.VOCAB == tuple(sorted(set(LS.VOCAB)))


