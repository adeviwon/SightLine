UNPORTABLE = [
    ("astral-characters",
     "Python indexes text by CODE POINT and len() counts code points; JS indexes "
     "by UTF-16 unit. A non-BMP character (e.g. U+1D552) shifts every offset. "
     "The recogniser alphabet is 0-9 A-Z and space, so no astral input exists."),
    ("non-ascii-digits",
     "Python \\d/isdigit()/str.isalnum() accept Unicode Nd and No ('1' variants, "
     "'2'); JS /[0-9]/ and \\p{N} are not the same set at the isdigit() edges. "
     "The recogniser alphabet is 0-9 A-Z and space."),
    ("non-ascii-case-folding",
     "str.upper() (Python) and String.prototype.toUpperCase() (JS) agree on ASCII "
     "but differ on '\\u0130', the German sharp s and others. The folded text is "
     "the recogniser's own uppercase alphabet, so this is unreachable."),
    ("python-wholeword-is-unicode",
     "Python's token-boundary test is str.isalnum() (Unicode L* + N*) and JS's is "
     "\\p{L}\\p{N}; the two agree for every character the recogniser can emit but "
     "are spelled differently, so a non-BMP/numeric-edge character is excluded."),
    ("line-text-not-a-string",
     "extract_fields' next-line search calls str(ln.get('text','')): Python renders "
     "None as 'None', JS String(null) as 'null'. The app's line records always "
     "carry a string text, so the JS reads a missing text as ''."),
    ("non-string-spot-fields",
     "int()/str() on a spot's line_index/start/end/label: str(None)='None' vs "
     "String(null)='null'. The app's spots come from spot_in_lines, which emits "
     "ints and strings, so the vectors carry ints and strings."),
    ("float-sort-of-equal-keys",
     "Sorted candidates tie on (-L, start, -score, label); a further tie would need "
     "identical (i, wl) and is impossible, so Python's Timsort and JS's stable "
     "sort cannot diverge. No case is excluded, this is recorded as checked."),
]


# ── the corpus: spotting ──────────────────────────────────────────────────────

def _perturbations(line):
    """Single-character substitution, deletion and insertion at every position.

    These are the near-miss / OCR-drift cases that sit just above and below the
    score gate, the deletion cases (which the shorter window is there to catch),
    and the token-boundary cases (which must NOT fire)."""
    out = []
    for i in range(len(line)):
        out.append(line[:i] + "X" + line[i + 1:])     # substitution
        out.append(line[:i] + line[i + 1:])           # deletion (OCR drop)
        out.append(line[:i] + "X" + line[i:])         # insertion (shifts alignment)
    return out


