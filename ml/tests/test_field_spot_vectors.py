    n = len(payload["vectors"])
    if a.count:
        print("%d vectors" % n)
        return 0
    if a.write:
        VECTORS.parent.mkdir(parents=True, exist_ok=True)
        VECTORS.write_text(json.dumps(payload, indent=1, sort_keys=True,
                                      ensure_ascii=False) + "\n", encoding="utf-8")
        _write_js_block(build_js_block())
        print("wrote %s: %d vectors (vocabulary %d labels)"
              % (VECTORS.relative_to(ROOT), n, len(LS.VOCAB)))
        return 0
    ap.print_usage()
    return 1


