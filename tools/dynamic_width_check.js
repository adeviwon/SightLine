/**
 * dynamic_width_check.js — is the recogniser ADAPTIVE to its graph's width?
 *
 * THE QUESTION
 * ------------
 * Two things have to be true before the dynamic-width graph can be swapped in
 * as a pure file replacement:
 *
 *   1. GRAPH  onnxruntime-web's WASM backend applies static-shape optimisations
 *             at session-creation time, so a graph that is dynamic in Python ORT
 *             is allowed to be REFUSED on the phone. `artifacts/crnn_dynamic.onnx`
 *             accepts [1,1,32,W] for any W in ml/src/export_dynamic.py --parity.
 *   2. APP     app/js/recognizer.js must FEED the graph the width the graph
 *             declares, or the swap does nothing: it used to build its tensor
 *             and its row stride at EXPORT_W, so a dynamic graph would have been
 *             handed a 320-wide padded tensor with a 320 stride forever.
 *
 * So this drives the APP'S OWN MODULE (app/js/recognizer.js — its init(),
 * recognise(), engineWidth() and decodeGreedy(), not a copy) against both
 * graphs, in WebKit (iOS Safari's engine) and Chromium, on real crops resized to
 * the fixture widths. It asserts the BRANCH, not just the numbers:
 *
 *   dynamic graph -> engineWidth() === 'dynamic', recognise() decodes all T at
 *                    the crop's NATURAL width (so `timesteps` must equal
 *                    PyTorch's T at that width — a padded run would return
 *                    T(320)=40, not T(W)), and the text must equal the PyTorch
 *                    reference decode at W.
 *   fixed graph   -> engineWidth() is a NUMBER equal to the width ORT reports
 *                    for that file when it refuses a wrong one (read here
 *                    separately, so a hardcoded 320 in the app cannot pass by
 *                    agreeing with itself), and recognise() must equal an
 *                    independent padded-to-that-width decode built HERE.
 *
 * The decoder is the app's own, so this cannot pass by decoding differently from
 * what we ship. Nothing here copies artifacts/crnn_dynamic.onnx over
 * app/models/crnn.onnx: the weights must come from the FINAL checkpoint, which
 * is still training. This proves the MECHANISM, not the artifact.
 *
 * Fixture (crop bytes + PyTorch reference decodes) is regenerated by:
 *   bash run.sh py ml/src/export_dynamic.py --fixture
 * Run:
 *   node app/tools/dynamic_width_check.js [--engine=webkit|chromium|both]
 * Exit 0 only when every assertion held in every engine that ran.
 */
"use strict";

const http = require("http");
const fs = require("fs");
const path = require("path");

const APP = path.resolve(__dirname, "..");
const ROOT = path.resolve(APP, "..");
const TIMEOUT_MS = 180000;

// The clamp realdata.MAX_W, and the crop cap ocr_engine passes to
// cropForRecognizer. It is NOT the served tensor width any more; the Python
// contract test (ml/tests/test_graph_width_contract.py) pins it to realdata.
const TRAINING_CLAMP = 320;

const pw = require("./pw_core.js")();
const chromeBin = require("./chrome_path.js")();

const MIME = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8", ".json": "application/json; charset=utf-8",
  ".wasm": "application/wasm", ".onnx": "application/octet-stream",
  ".png": "image/png", ".css": "text/css",
};

// A blank page: the app's index.html would boot pipeline.js, the service worker
// and the whole scan path, none of which this check needs — it only needs an
// HTTP origin so a module import and a wasm fetch are legal.
const BLANK = "<!doctype html><meta charset=utf-8><title>dyn width check</title>";

/** Static server: app/ at the root, the repo (artifacts/) under /repo/. */
function serve() {
  const server = http.createServer((req, res) => {
    const p = decodeURIComponent(new URL(req.url, "http://localhost").pathname);
    if (p === "/__dyncheck.html") {
      res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
      return res.end(BLANK);
    }
    const base = p.startsWith("/repo/") ? ROOT : APP;
    const file = path.join(base, p.startsWith("/repo/") ? p.slice("/repo/".length) : p);
    if (!file.startsWith(base) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
      res.writeHead(404, { "Content-Type": "text/plain" });
      return res.end("not found: " + p);
    }
    res.writeHead(200, { "Content-Type": MIME[path.extname(file)] || "application/octet-stream",
                         "Cache-Control": "no-store" });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise((r) => server.listen(0, "127.0.0.1", () => r(server)));
}

/**
 * Everything that runs INSIDE the page. Returns a report or an error object.
 *
 * A real function, not a string: Playwright serialises the source and rejects
 * anything that closes over outer scope, so this takes everything through
 * `cfg` and references nothing else.
 */
async function inPage(cfg) {
  try {
    const ORT = await import(cfg.ortUrl);
    const env = ORT.env || (ORT.env = {});
    env.wasm = env.wasm || {};
    env.wasm.wasmPaths = cfg.wasmDir;
    env.wasm.numThreads = 1;

    // The app's own module. Everything below goes through it: if the app pads,
    // this pads; if it feeds the natural width, this feeds the natural width.
    const rec = await import(cfg.recUrl);
    const crop = (k) => Uint8Array.from(atob(cfg.crops[k]), (ch) => ch.charCodeAt(0));
    // Normalised [-1,1] like the training transform: +1 paper, -1 ink. The
    // fixture bytes are the same pixels Python fed, so the only difference that
    // can remain is the tensor's SHAPE.
    const norm = (u8, i) => (u8[i] / 255 - 0.5) / 0.5;
    const argmaxDecode = (logits, limit) => {
      const C = logits.dims[2], data = logits.data;
      const n = Math.min(limit, logits.dims[1]);
      const idx = new Int32Array(n);
      for (let t = 0; t < n; t++) {
        let best = 0, bestVal = -Infinity;
        for (let c = 0; c < C; c++) { const v = data[t * C + c]; if (v > bestVal) { bestVal = v; best = c; } }
        idx[t] = best;
      }
      return rec.decodeGreedy(idx, n);        // the app's decoder, not a copy
    };

    const out = { ok: true, constants: { trainingClamp: rec.TRAINING_CLAMP, exportW: rec.EXPORT_W,
                  clampExpected: cfg.trainingClamp }, branches: {} };
    out.ok = out.ok && rec.TRAINING_CLAMP === cfg.trainingClamp
                     && rec.EXPORT_W === rec.TRAINING_CLAMP;

    // ── branch 1: the DYNAMIC artifact ────────────────────────────────────
    // reset() clears the memoised session, so init() re-reads the width from
    // THIS file instead of reusing the previous graph's conclusion.
    rec.reset();
    await rec.init(cfg.dynamicUrl);
    const dynRows = [];
    for (const W of cfg.widths) {
      const k = String(W);
      const r = await rec.recognise(crop(k), W);
      dynRows.push({
        w: W, got: r.text, py: cfg.pyNatural[k], match: r.text === cfg.pyNatural[k],
        t: r.timesteps, pyT: cfg.pyNaturalT[k], tMatch: r.timesteps === cfg.pyNaturalT[k],
        error: r.error || null,
      });
    }
    out.branches.dynamic = { engineWidth: rec.engineWidth(), rows: dynRows };
    out.ok = out.ok && rec.engineWidth() === "dynamic";
    for (const r of dynRows) out.ok = out.ok && r.match && r.tMatch && !r.error;

    // ── branch 2: the SHIPPED fixed-width graph ───────────────────────────
    rec.reset();
    await rec.init(cfg.fixedUrl);
    const fixedWidth = rec.engineWidth();

    // The graph's OWN number, read independently of the app: ORT names the
    // declared width when it refuses a tensor built at another one. If the app
    // hardcoded 320 and the file were 256, this is what catches it.
    const raw = await ORT.InferenceSession.create(cfg.fixedUrl, { executionProviders: ["wasm"] });
    let declared = null, refusal = null;
    try {
      await raw.run({ input: new ORT.Tensor("float32", new Float32Array(32 * 63), [1, 1, 32, 63]) });
    } catch (e) {
      refusal = e && e.message ? e.message : String(e);
      const m = /index:\s*3\s+Got:\s*\d+\s+Expected:\s*(\d+)/.exec(refusal);
      if (m) declared = Number(m[1]);
    }

    // The padded path's reference, built HERE — pad to the graph width on a
    // width stride, decode only timestepsFor(contentWidth) frames. Independent
    // of the app's buildInput, so a stride/shape disagreement cannot pass.
    const fixedRows = [];
    for (const W of cfg.widths) {
      const k = String(W), u8 = crop(k);
      const x = new Float32Array(32 * fixedWidth);
      for (let y = 0; y < 32; y++) {
        for (let xx = 0; xx < W; xx++) x[y * fixedWidth + xx] = norm(u8, y * W + xx);
      }
      const ref = argmaxDecode(
        (await raw.run({ input: new ORT.Tensor("float32", x, [1, 1, 32, fixedWidth]) })).logits,
        rec.timestepsFor(W));
      const app = await rec.recognise(u8, W);
      fixedRows.push({
        w: W, got: app.text, ref, match: app.text === ref,
        nat: cfg.pyNatural[k], agreesWithNatural: app.text === cfg.pyNatural[k],
        pyShipped: cfg.pyShipped[k], t: app.timesteps, error: app.error || null,
      });
    }
    out.branches.fixed = { engineWidth: fixedWidth, declared, refusal: refusal ? refusal.split("\n")[0] : null, rows: fixedRows };
    out.ok = out.ok && typeof fixedWidth === "number" && fixedWidth === declared && declared !== null;
    for (const r of fixedRows) out.ok = out.ok && r.match && !r.error;

    return out;
  } catch (e) {
    const msg = (e && e.name ? e.name + ": " : "") + (e && e.message ? e.message : String(e));
    const st = e && e.stack ? String(e.stack).split(String.fromCharCode(10)).slice(0, 4).join(" | ") : null;
    return { ok: false, error: msg, stack: st };
  }
}

async function runEngine(engine, url, fixture, base) {
  const report = { engine, refused: false, error: null, branches: null, logs: [] };
  let browser = null;
  try {
    browser = engine === "webkit"
      ? await pw.webkit.launch()
      : await pw.chromium.launch({ executablePath: chromeBin });
    const page = await browser.newPage();
    page.setDefaultTimeout(TIMEOUT_MS);
    // The recogniser LOGS the width it chose, and logs a warning when it could
    // not read one. Without this, a fallback to the clamp would print the same
    // "engine.width = 320" as a successful probe and this check could not tell
    // them apart.
    const logs = report.logs;
    page.on("console", (m) => { try { logs.push(m.type() + ": " + m.text()); } catch (e) { /* gone */ } });
    await page.goto(url, { waitUntil: "domcontentloaded" });
    const res = await page.evaluate(inPage, {
      ortUrl: base + "vendor/ort/ort.min.mjs",
      wasmDir: base + "vendor/ort/",
      recUrl: base + "js/recognizer.js",
      fixedUrl: base + "models/crnn.onnx",
      dynamicUrl: base + "repo/artifacts/crnn_dynamic.onnx",
      crops: fixture.crops, widths: fixture.widths,
      pyNatural: fixture.py_natural, pyNaturalT: fixture.py_natural_t,
      pyShipped: fixture.py_shipped, trainingClamp: TRAINING_CLAMP,
    });
    if (!res) { report.refused = true; report.error = "page.evaluate returned undefined"; }
    else if (!res.ok && res.error) { report.refused = true; report.error = res.error; report.stack = res.stack; }
    else { report.branches = res.branches; report.constants = res.constants; report.rows_ok = res.ok; }
  } catch (e) {
    report.refused = true;
    report.error = (e && e.message ? e.message : String(e));
  } finally {
    if (browser) { try { await browser.close(); } catch (e) { /* gone */ } }
  }
  return report;
}

const H = (s, n) => String(s).padEnd(n);

function printReport(r) {
  console.log("\n── " + r.engine + " ─────────────────────────────────────────");
  if (r.refused) {
    console.log("  ADAPTIVE-WIDTH CHECK REFUSED");
    console.log("  error: " + r.error);
    if (r.stack) console.log("  at:    " + r.stack);
    return false;
  }
  const b = r.branches || {};
  const c = r.constants || {};
  let ok = true;

  // The recogniser's own log lines: 'engine.width = ...' for each branch, and a
  // warning if it ever had to fall back instead of reading the width.
  const widthLogs = (r.logs || []).filter((l) => l.includes("engine.width"));
  const fallback = (r.logs || []).filter((l) => l.includes("could not read the graph's width"));
  for (const l of widthLogs) console.log("  log: " + l);
  if (fallback.length) {
    console.log("  log: " + fallback.join("\n  log: "));
    console.log("  the tried-and-fell-back path was taken — the width was NOT read from"
                + " the session, so nothing above proves the app is adaptive");
  }
  ok = ok && fallback.length === 0 && widthLogs.length >= 2;

  console.log("  constants: TRAINING_CLAMP=" + c.trainingClamp + " EXPORT_W=" + c.exportW
              + " (expected clamp " + c.clampExpected + ")");
  ok = ok && c.trainingClamp === c.clampExpected && c.exportW === c.trainingClamp;

  const d = b.dynamic || {};
  console.log("\n  DYNAMIC graph (artifacts/crnn_dynamic.onnx) — must serve the NATURAL width");
  console.log("    app engine.width = " + JSON.stringify(d.engineWidth)
              + (d.engineWidth === "dynamic" ? "  OK" : "  NO — expected 'dynamic'"));
  ok = ok && d.engineWidth === "dynamic";
  console.log("    " + H("W", 4) + " " + H("app text", 24) + " " + H("torch @natural", 24)
              + " " + H("T", 3) + " " + H("torch T", 3) + "  text  T");
  for (const x of (d.rows || [])) {
    ok = ok && x.match && x.tMatch && !x.error;
    console.log("    " + String(x.w).padStart(4) + " " + H(JSON.stringify(x.got), 24) + " "
      + H(JSON.stringify(x.py), 24) + " " + H(x.t, 3) + " " + H(x.pyT, 3) + "  "
      + (x.match ? "OK " : "NO ") + "  " + (x.tMatch ? "OK" : "NO")
      + (x.error ? "  error: " + x.error : ""));
  }

  const f = b.fixed || {};
  console.log("\n  FIXED graph (app/models/crnn.onnx) — must PAD to the graph's own width");
  console.log("    app engine.width = " + JSON.stringify(f.engineWidth)
              + "  ORT declares        = " + JSON.stringify(f.declared)
              + (typeof f.engineWidth === "number" && f.engineWidth === f.declared ? "  OK" : "  NO"));
  if (f.refusal) console.log("    (ORT refused width 63: " + f.refusal + ")");
  ok = ok && typeof f.engineWidth === "number" && f.engineWidth === f.declared;
  console.log("    " + H("W", 4) + " " + H("app text", 24) + " " + H("padded ref", 24)
              + " " + H("torch @natural", 24) + " " + H("torch pad256", 24) + "  match  natural");
  for (const x of (f.rows || [])) {
    ok = ok && x.match && !x.error;
    console.log("    " + String(x.w).padStart(4) + " " + H(JSON.stringify(x.got), 24) + " "
      + H(JSON.stringify(x.ref), 24) + " " + H(JSON.stringify(x.nat), 24) + " "
      + H(JSON.stringify(x.pyShipped), 24) + "  " + (x.match ? "OK " : "NO ") + "     "
      + (x.agreesWithNatural ? "yes" : "no")
      + (x.error ? "  error: " + x.error : ""));
  }

  ok = ok && r.rows_ok === true;
  return ok;
}

(async () => {
  const arg = (process.argv.find((a) => a.startsWith("--engine=")) || "").split("=")[1];
  const engines = arg === "webkit" || arg === "chromium" ? [arg] : ["webkit", "chromium"];
  const fixturePath = path.join(ROOT, "artifacts", "dynamic_width_fixture.json");
  if (!fs.existsSync(fixturePath)) {
    console.error("missing " + fixturePath + " — run: bash run.sh py ml/src/export_dynamic.py --fixture");
    process.exit(2);
  }
  const fixture = JSON.parse(fs.readFileSync(fixturePath, "utf8"));

  const server = await serve();
  const base = "http://127.0.0.1:" + server.address().port + "/";
  const results = {};
  let allOk = true;
  for (const e of engines) {
    const r = await runEngine(e, base + "__dyncheck.html", fixture, base);
    results[e] = r;
    allOk = printReport(r) && allOk;
  }
  server.close();

  if (process.env.DYN_JSON) {
    fs.writeFileSync(process.env.DYN_JSON, JSON.stringify(results, null, 1) + "\n");
  }

  console.log("\n" + (allOk ? "ADAPTIVE WIDTH OK in " + engines.join(" + ")
                           : "ADAPTIVE WIDTH FAILED in " + engines.join(" + ")));
  process.exit(allOk ? 0 : 1);
})();
