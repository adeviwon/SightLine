/**
 * word_beam.js — word-level-LM CTC decoding, in the browser, AFTER the ONNX graph.
 *
 * WHY THIS EXISTS (measured, not assumed)
 * ---------------------------------------
 * `ml/src/eval_decode_sweep.py` decodes the SAME logits of the shipped
 * recogniser three ways on 1,000 held-out crops:
 *
 *   greedy                                        68.40% exact   CER 0.1715
 *   beam 4, no LM                                 68.90% exact   CER 0.1719
 *   beam 4 + word LM (lexicon trie), alpha 0.25   71.10% exact   CER 0.1740
 *                                                 (+32 / -5 crops, exact McNemar p < 1e-4)
 *
 * The BEAM is worth ~0.5 pt — the doc's reading of the literature (a plain beam
 * is a dead heat) is what this confirms. The WORD LM is worth 2.7 pts, and it is
 * the only part that earns its place in the shipped bundle.
 *
 * WHAT THE WORD LM IS
 * -------------------
 * A trie over `data/lexicon.txt` (2,878 tokens: document keys, units, medicine
 * names and the digit strings real fields take). Expressed as a per-character
 * score `P(c | word-so-far) = count(node(w+c)) / count(node(w))`, so it drops
 * into the beam's existing char-emit hook and the search itself is untouched.
 * Two deliberate asymmetries, both measured-needed:
 *
 *  - completing a word nobody serves costs PASS_PENALTY; completing a real word
 *    costs 0;
 *  - a LETTER inside a digit run costs PASS_PENALTY (that is the O/0, I/1, S/5
 *    confusion the product must not read — "0A7E01102026"), while an unseen
 *    NUMBER only costs DIGIT_PENALTY (-0.5), because account numbers and dates
 *    are open-ended and punishing them would make the decoder corrupt reads that
 *    were already right.
 *
 * These constants and the search below mirror `ml/src/ctc_decode.py` +
 * `ml/src/word_lm.py` exactly; `app/tools/word_lm_parity.js` pins that on real
 * crops against vectors generated by the Python side.
 */

const NEG_INF = -1e30;
export const EPS = 0.5;
export const PASS_PENALTY = -6.0;
export const DIGIT_PENALTY = -0.5;

/** log(exp(a) + exp(b)) — mirrors ctc_decode._lae, including the two-branch
 * shortcut, so the two implementations round the same way. */
export function lae(a, b) {
  if (b > a) { const t = a; a = b; b = t; }
  if (b <= NEG_INF || a - b > 30.0) return a;
  return a + Math.log1p(Math.exp(b - a));
}

function isDigitRun(w) {
  for (let i = 0; i < w.length; i++) if (w[i] < "0" || w[i] > "9") return false;
  return true;
}

/**
 * The lexicon trie: {p: passWeight, t: terminalWeight, c: {char: node}}.
 *
 * Every SCORING CONSTANT comes out of the artifact's own `meta` and not from a
 * literal in this file. The Python side is what the sweeps tune; a constant
 * retyped here is a second copy that goes stale the first time a knob moves, and
 * the failure is silent — the browser just decodes slightly differently from the
 * model the numbers were measured on. Module-level defaults remain only for a
 * trie exported before `meta.beta` existed.
 */
export class WordTrie {
  constructor(json) {
    this.root = json.root;
    const meta = json.meta || {};
    this.words = meta.words || 0;
    this.total = meta.total || 0;
    this.penalty = meta.penalty === undefined ? PASS_PENALTY : meta.penalty;
    this.digitPenalty = meta.penalty_digit === undefined ? DIGIT_PENALTY : meta.penalty_digit;
    this.beta = meta.beta === undefined ? 0.0 : meta.beta;
    this.eps = meta.eps === undefined ? EPS : meta.eps;
    // WORD BIGRAMS. The trie alone knows `TWICE` and `DAILY` are words; only the
    // bigram knows `TWICE DAILY` is a phrase and `DAILY TWICE` is not — which is the
    // half of a word LM a lexicon cannot express. Absent from older artifacts, and
    // weight 0 keeps the trie-only behaviour exactly, so this cannot change what
    // ships until a measurement says the pairs earn their bytes.
    this.bigramW = meta.bi_w === undefined ? 0.0 : meta.bi_w;
    this.bigramVocab = meta.bi_vocab || 1;
    this.bigrams = new Map();
    this.bigramPrev = new Map();
    const bi = json.bi || {};
    for (const k of Object.keys(bi)) {
      const i = k.indexOf("\u0000");
      const prev = i < 0 ? k : k.slice(0, i);
      const next = i < 0 ? "" : k.slice(i + 1);
      this.bigrams.set(prev + "\u0000" + next, bi[k]);
      this.bigramPrev.set(prev, (this.bigramPrev.get(prev) || 0) + bi[k]);
    }
  }

  static async load(url) {
    const res = await fetch(url);
    if (!res.ok) throw new Error("word trie HTTP " + res.status);
    return new WordTrie(await res.json());
  }

  /** The node for a word (null if no lexicon word has it as a prefix). */
  _node(w) {
    let node = this.root;
    for (let i = 0; i < w.length; i++) {
      node = node.c[w[i]];
      if (!node) return null;
    }
    return node;
  }

  /**
   * Mirrors ml/src/word_lm.WordLM.bigram_logp — log P(w | previous word).
   *
   * `prefix` ends with `w`, so the context is the word before it. An unseen pair is
   * priced as one pseudo-count over that context's total rather than as a hard zero:
   * a dose panel that says something the panels never said must stay decodable, and
   * a -Infinity here would silently prune every novel reading out of the beam.
   */
  bigramLogp(prefix, w) {
    const words = prefix.split(" ");
    if (words.length < 2) return 0.0;          // nothing to condition on
    const prev = words[words.length - 2];
    if (prev === w) return 0.0;                // a repeated word is not evidence
    const total = this.bigramPrev.get(prev) || 0;
    if (total <= 0) return 0.0;                // an unseen context says nothing
    const seen = this.bigrams.get(prev + "\u0000" + w) || 0;
    return Math.log((seen + this.eps) / (total + this.eps * this.bigramVocab));
  }

  /** Mirrors ml/src/word_lm.WordLM.logp — raw log-prob; the caller weights it. */
  logp(prefix, ch) {
    const sp = prefix.lastIndexOf(" ");
    const w = sp < 0 ? prefix : prefix.slice(sp + 1);
    if (ch === " ") {
      if (!w) return 0.0;
      const node = this._node(w);
      const done = !!(node && node.t > 0);
      let score = done ? this.beta              // a word we serve, plus the bonus
        : this.beta + (isDigitRun(w) ? this.digitPenalty : this.penalty);
      if (this.bigramW && this.bigrams.size) {
        score += this.bigramW * this.bigramLogp(prefix, w);
      }
      return score;
    }
    const node = this._node(w);
    if (node) {
      const child = node.c[ch];
      if (child && child.p > 0) {
        return Math.log((child.p + this.eps) / (node.p + this.eps));
      }
    }
    if (ch >= "0" && ch <= "9" && (w === "" || isDigitRun(w))) return this.digitPenalty;
    return this.penalty;
  }
}

/**
 * Log-softmax of one logits row into `out` (float64), the transform the Python
 * evaluation applies before decoding (`torch.log_softmax`). Computed in double
 * precision deliberately: the Python side is float32 and a float32 sum here
 * would drift by enough to flip a near-tie the parity vectors would then blame
 * on the search.
 */
export function logSoftmaxRow(data, base, C, out) {
  let max = -Infinity;
  for (let c = 0; c < C; c++) if (data[base + c] > max) max = data[base + c];
  let sum = 0;
  for (let c = 0; c < C; c++) sum += Math.exp(data[base + c] - max);
  const logSum = Math.log(sum);
  for (let c = 0; c < C; c++) out[c] = data[base + c] - max - logSum;
  return out;
}

/**
 * CTC prefix beam search with optional word-LM shallow fusion.
 *
 * Mirrors `ctc_decode.beam_search`, including the bookkeeping that is easy to
 * get wrong: a prefix carries TWO scores (alignments ending in a blank and in
 * its last character), and a repeat character is reachable from the blank-ended
 * score only — treated as a new character it would double every repeated digit.
 *
 * @param {Float64Array|Float32Array} logProbs  row-major [T][C], already log-softmaxed
 * @param {number} T timesteps to decode (never the padded tensor width)
 * @param {number} C classes (38: blank + 37 charset)
 * @param {string} charset 37 chars, index c-1 => charset[c-1]
 * @param {object} opts {beam, blank, lm, alpha}
 * @returns {{text: string, logProb: number}}
 */
export function beamDecode(logProbs, T, C, charset, opts) {
  const o = opts || {};
  const beam = o.beam || 8;
  const blank = o.blank === undefined ? 0 : o.blank;
  const lm = o.lm || null;
  const alpha = o.alpha || 0;
  const useLM = !!lm && alpha > 0;

  let beams = new Map([["", [0.0, NEG_INF]]]);
  for (let t = 0; t < T; t++) {
    const base = t * C;
    const lBlank = logProbs[base + blank];
    const nxt = new Map();
    for (const [prefix, scores] of beams) {
      const pB = scores[0], pNB = scores[1];
      const pTot = lae(pB, pNB);
      let e = nxt.get(prefix);
      if (!e) { e = [NEG_INF, NEG_INF]; nxt.set(prefix, e); }
      e[0] = lae(e[0], pTot + lBlank);
      const last = prefix.length ? prefix[prefix.length - 1] : "";
      for (let c = 0; c < C; c++) {
        if (c === blank) continue;
        const ch = charset[c - 1];
        if (ch === undefined) continue;
        const lpc = logProbs[base + c];
        if (prefix && ch === last) {
          let ext = nxt.get(prefix + ch);
          if (!ext) { ext = [NEG_INF, NEG_INF]; nxt.set(prefix + ch, ext); }
          const lpcLM = useLM ? lpc + alpha * lm.logp(prefix, ch) : lpc;
          ext[1] = lae(ext[1], pB + lpcLM);
          e[1] = lae(e[1], pNB + lpc);
        } else {
          const key = prefix + ch;
          let ext = nxt.get(key);
          if (!ext) { ext = [NEG_INF, NEG_INF]; nxt.set(key, ext); }
          const lpcLM = useLM ? lpc + alpha * lm.logp(prefix, ch) : lpc;
          ext[1] = lae(ext[1], pTot + lpcLM);
        }
      }
    }
    if (nxt.size > beam) {
      const ranked = [...nxt.entries()]
        .sort((a, b) => lae(b[1][0], b[1][1]) - lae(a[1][0], a[1][1]))
        .slice(0, beam);
      nxt.clear();
      for (const [k, v] of ranked) nxt.set(k, v);
    }
    beams = nxt.size ? nxt : beams;
  }
  let best = "", bestScore = NEG_INF;
  for (const [prefix, s] of beams) {
    const total = lae(s[0], s[1]);
    if (total > bestScore) { bestScore = total; best = prefix; }
  }
  return { text: best, logProb: bestScore };
}
