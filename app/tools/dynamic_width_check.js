/**
 * dynamic_width_check.js — does onnxruntime-web RUN the dynamic-width CRNN?
 *
 * THE QUESTION
 * ------------
 * `artifacts/crnn_dynamic.onnx` accepts [1,1,32,W] for ANY W in Python ORT and
 * reproduces eager PyTorch to ~1e-5 (ml/src/export_dynamic.py --parity). But the
 * shipped target is onnxruntime-web inside Safari on iOS, and the WASM backend
 * applies static-shape optimisations at session-creation time. A graph that is
 * dynamic on the laptop is allowed to be REJECTED on the phone, and nothing in
 * the Python lane can tell us which. This drives the real thing: ORT-web, the
 * app's own vendored runtime (app/vendor/ort/), loading the dynamic graph and
 * running it at several real crop widths, in WebKit (iOS Safari's engine) and
 * Chromium.
 *
 * WHAT IT ASSERTS
 * ---------------
 * For each width in the fixture (artifacts/dynamic_width_fixture.json, written
 * by export_dynamic.write_fixture): run the dynamic graph at its NATURAL width
 * and require the greedy CTC decode to equal the PyTorch reference decode
 * recorded by the Python side. It also reproduces the SHIPPED path (same crop
 * right-padded to 256, decode limited to the app's timestepsFor window) so the
 * browser shows the padding bug too, not just the fix.
 *
 * The decoder is imported from app/js/recognizer.js — the app's own — so this
 * cannot pass by decoding differently from the thing we ship.
 *
 * Fixture is regenerated by:  bash run.sh py ml/src/export_dynamic.py --fixture
 * Run:                        node app/tools/dynamic_width_check.js [--engine=webkit|chromium|both]
 * Exit 0 only when every width matched in every engine that ran.
 */
"use strict";

const http = require("http");
const fs = require("fs");
const path = require("path");

const APP = path.resolve(__dirname, "..");
const ROOT = path.resolve(APP, "..");
const TIMEOUT_MS = 180000;

const pw = require("./pw_core.js")();
const chromeBin = require("./chrome_path.js")();

const MIME = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8", ".json": "application/json; charset=utf-8",
  ".wasm": "application/wasm", ".onnx": "application/octet-stream",
  ".png": "image/png", ".css": "text/css",
};

// A blank page: the app's index.html would boot pipeline.js, the service worker
// and the whole scan path, none of which this check needs — it only needs an
// HTTP origin so a module import and a wasm fetch are legal.
const BLANK = "<!doctype html><meta charset=utf-8><title>dyn width check</title>";

/** Static server: app/ at the root, the repo (artifacts/) under /repo/. */
function serve() {
  const server = http.createServer((req, res) => {
    const p = decodeURIComponent(new URL(req.url, "http://localhost").pathname);
    if (p === "/__dyncheck.html") {
      res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
      return res.end(BLANK);
    }
    const base = p.startsWith("/repo/") ? ROOT : APP;
    const file = path.join(base, p.startsWith("/repo/") ? p.slice("/repo/".length) : p);
    if (!file.startsWith(base) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
      res.writeHead(404, { "Content-Type": "text/plain" });
      return res.end("not found: " + p);
    }
    res.writeHead(200, { "Content-Type": MIME[path.extname(file)] || "application/octet-stream",
                         "Cache-Control": "no-store" });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise((r) => server.listen(0, "127.0.0.1", () => r(server)));
}

/**
 * Everything that runs INSIDE the page. Returns a report or an error object.
 *
 * A real function, not a string: Playwright serialises the source and rejects
 * anything that closes over outer scope, so this takes everything through
 * `cfg` and references nothing else.
 */
async function inPage(cfg) {
  try {
    const ORT = await import(cfg.ortUrl);
    const env = ORT.env || (ORT.env = {});
    env.wasm = env.wasm || {};
    env.wasm.wasmPaths = cfg.wasmDir;
    env.wasm.numThreads = 1;

    // The app's own decoder: this check must not be able to pass by decoding
    // differently from the shipped recogniser.
    const rec = await import(cfg.recUrl);
    const decodeGreedy = rec.decodeGreedy, timestepsFor = rec.timestepsFor;

    const session = await ORT.InferenceSession.create(cfg.modelUrl, {
      executionProviders: ["wasm"],
    });

    const decode = (logits, T, limit) => {
      const C = logits.dims[2], data = logits.data;
      const n = Math.min(limit, T);
      const idx = new Int32Array(n);
      for (let t = 0; t < n; t++) {
        let best = 0, bestVal = -Infinity;
        const b = t * C;
        for (let c = 0; c < C; c++) { const v = data[b + c]; if (v > bestVal) { bestVal = v; best = c; } }
        idx[t] = best;
      }
      return decodeGreedy(idx, n);
    };

    const rows = [];
    for (const W of cfg.widths) {
      const k = String(W);
      const u8 = Uint8Array.from(atob(cfg.crops[k]), (ch) => ch.charCodeAt(0));
      const x = new Float32Array(32 * W);
      for (let i = 0; i < x.length; i++) x[i] = (u8[i] / 255 - 0.5) / 0.5;

      // (1) natural width — the whole point of the dynamic graph
      const nat = await session.run({ input: new ORT.Tensor("float32", x, [1, 1, 32, W]) });
      const T = nat.logits.dims[1];
      const natText = decode(nat.logits, T, T);

      // (2) the SHIPPED path: pad to 256, decode only timestepsFor(content)
      const pad = new Float32Array(32 * 256);
      for (let y = 0; y < 32; y++) pad.set(x.subarray(y * W, y * W + W), y * 256);
      const sh = await session.run({ input: new ORT.Tensor("float32", pad, [1, 1, 32, 256]) });
      const shText = decode(sh.logits, sh.logits.dims[1], timestepsFor(W));

      rows.push({ w: W, t: T, nat: natText, pyNat: cfg.pyNatural[k],
                  natMatch: natText === cfg.pyNatural[k],
                  sh: shText, pySh: cfg.pyShipped[k],
                  shMatch: shText === cfg.pyShipped[k] });
    }
    return { ok: true, rows, inputName: session.inputNames[0] };
  } catch (e) {
    const msg = (e && e.name ? e.name + ": " : "") + (e && e.message ? e.message : String(e));
    const st = e && e.stack ? String(e.stack).split(String.fromCharCode(10)).slice(0, 4).join(" | ") : null;
    return { ok: false, error: msg, stack: st };
  }
}

async function runEngine(engine, url, fixture, base) {
  const report = { engine, refused: false, error: null, rows: [] };
  let browser = null;
  try {
    browser = engine === "webkit"
      ? await pw.webkit.launch()
      : await pw.chromium.launch({ executablePath: chromeBin });
    const page = await browser.newPage();
    page.setDefaultTimeout(TIMEOUT_MS);
    await page.goto(url, { waitUntil: "domcontentloaded" });
    const res = await page.evaluate(inPage, {
      ortUrl: base + "vendor/ort/ort.min.mjs",
      wasmDir: base + "vendor/ort/",
      recUrl: base + "js/recognizer.js",
      modelUrl: base + "repo/artifacts/crnn_dynamic.onnx",
      crops: fixture.crops, widths: fixture.widths,
      pyNatural: fixture.py_natural, pyShipped: fixture.py_shipped,
    });
    if (!res) { report.refused = true; report.error = "page.evaluate returned undefined"; }
    else if (!res.ok) { report.refused = true; report.error = res.error; report.stack = res.stack; }
    else report.rows = res.rows;
  } catch (e) {
    report.refused = true;
    report.error = (e && e.message ? e.message : String(e));
  } finally {
    if (browser) { try { await browser.close(); } catch (e) { /* gone */ } }
  }
  return report;
}

function printReport(r) {
  console.log("\n── " + r.engine + " ─────────────────────────────────────────");
  if (r.refused) {
    console.log("  DYNAMIC-WIDTH REFUSED");
    console.log("  error: " + r.error);
    if (r.stack) console.log("  at:    " + r.stack);
    return false;
  }
  const H = (s, n) => String(s).padEnd(n);
  console.log("  " + H("W", 4) + " " + H("T", 3) + "  " + H("dynamic@W (browser)", 22)
              + " " + H("torch", 22) + " dyn  " + H("shipped@256", 22) + " "
              + H("torch", 22) + " ship");
  let ok = true;
  for (const x of r.rows) {
    ok = ok && x.natMatch;
    console.log("  " + String(x.w).padStart(4) + " " + String(x.t).padStart(3) + "  "
      + H(JSON.stringify(x.nat), 22) + " " + H(JSON.stringify(x.pyNat), 22) + " "
      + (x.natMatch ? "OK " : "NO ") + " "
      + H(JSON.stringify(x.sh), 22) + " " + H(JSON.stringify(x.pySh), 22) + " "
      + (x.shMatch ? "OK" : "NO"));
  }
  return ok;
}

(async () => {
  const arg = (process.argv.find((a) => a.startsWith("--engine=")) || "").split("=")[1];
  const engines = arg === "webkit" || arg === "chromium" ? [arg] : ["webkit", "chromium"];
  const fixturePath = path.join(ROOT, "artifacts", "dynamic_width_fixture.json");
  if (!fs.existsSync(fixturePath)) {
    console.error("missing " + fixturePath + " — run: bash run.sh py ml/src/export_dynamic.py --fixture");
    process.exit(2);
  }
  const fixture = JSON.parse(fs.readFileSync(fixturePath, "utf8"));

  const server = await serve();
  const base = "http://127.0.0.1:" + server.address().port + "/";
  const results = {};
  let allOk = true;
  for (const e of engines) {
    const r = await runEngine(e, base + "__dyncheck.html", fixture, base);
    results[e] = r;
    allOk = printReport(r) && allOk;
  }
  server.close();

  if (process.env.DYN_JSON) {
    fs.writeFileSync(process.env.DYN_JSON, JSON.stringify(results, null, 1) + "\n");
  }

  console.log("\n" + (allOk ? "DYNAMIC WIDTH OK in " + engines.join(" + ")
                           : "DYNAMIC WIDTH FAILED in " + engines.join(" + ")));
  process.exit(allOk ? 0 : 1);
})();
